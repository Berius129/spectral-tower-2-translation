"""Generate docs/ROOTS.md: every Root with its input code, from the disc.

Usage: python3 tools/roots_table.py "path/to/Spectral Tower II (Japan).bin"

Root records in SLPS_011.79 start at file offset 0xC3B8C, 0x1C bytes each:
  +0x00 name (cp932, NUL padded)
  +0x14 u32  code typed at the Tree of Destiny (8 digits)
  +0x18 u16  usable skill types, 12 bits, bit 11 = Brawl ... bit 0 = Arts
             (same order as the Root list header in the status screen)
  +0x1A u8   chest hits (attempts when opening a treasure chest)
The skill-type and chest-hit meanings are inferred from the data and the
Root descriptions, not from the game's code.
"""
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
import exestrings
import psxiso

ROOT = os.path.join(os.path.dirname(__file__), '..')
FIRST, STRIDE, COUNT = 0xC3B8C, 0x1C, 140
TYPES = ['Brawl', 'Sword', 'Prayer', 'Void', 'Fire', 'Wind', 'Water', 'Earth',
         'Wisdom', 'Nature', 'Tricks', 'Arts']


def main(bin_path):
    exe = psxiso.Image(bin_path).read(exestrings.PATH)
    script = json.load(open(os.path.join(ROOT, 'script', 'SLPS_011.79.json'), encoding='utf-8'))
    english = {int(e['offset'], 16): e['en'] for e in script}
    rows = []
    for i in range(COUNT):
        off = FIRST + i * STRIDE
        jp = exe[off:exe.find(b'\0', off)].decode('cp932')
        code, = struct.unpack_from('<I', exe, off + 0x14)
        mask, = struct.unpack_from('<H', exe, off + 0x18)
        hits = exe[off + 0x1A]
        types = ', '.join(t for b, t in enumerate(TYPES) if mask >> (11 - b) & 1) or '-'
        rows.append(f'| {i} | {english.get(off) or jp} | {jp} | `{code // 10000:04d}-{code % 10000:04d}` '
                    f'| {types} | {hits} |')
    out = os.path.join(ROOT, 'docs', 'ROOTS.md')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8') as f:
        f.write('# Roots\n\n'
                'Codes to enter at the Tree of Destiny (Epsilon → Enter a Root). '
                'Generated by `tools/roots_table.py` from the game data.\n\n'
                '"Skill types" and "Chest hits" are read from the Root records and '
                'interpreted from the data and descriptions; they are not confirmed '
                'against the game code. Changing Root unequips your gear.\n\n'
                '| # | Root | Japanese | Code | Skill types | Chest hits |\n'
                '|---|---|---|---|---|---|\n')
        f.write('\n'.join(rows) + '\n')
    print(f'{len(rows)} Roots -> {os.path.relpath(out, ROOT)}')


if __name__ == '__main__':
    main(sys.argv[1])
